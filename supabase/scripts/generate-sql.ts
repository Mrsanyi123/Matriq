/**
 * Generates SQL from the TypeScript sources of truth:
 *
 *   tsx scripts/generate-sql.ts reference  → migrations/20261029000800_reference_data.sql
 *   tsx scripts/generate-sql.ts seed       → seed/demo_curriculum.sql (local dev only)
 *
 * The reference migration was generated once and committed; regenerate it
 * only into a NEW migration if the catalogue changes. supabase/tests checks
 * that the database and the TypeScript catalogue agree.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ACHIEVEMENTS } from '@matriq/core';
import {
  DEMO_CHAPTERS,
  DEMO_EDITION,
  DEMO_SOURCE,
  DEMO_UNITS,
  GRADES,
  STREAMS_CATALOG,
  SUBJECTS,
  demoId,
} from '@matriq/demo-content';
import { STREAM_GRADE_LEVELS } from '@matriq/types';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** SQL literal for a JS value. */
export function lit(value: unknown): string {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (Array.isArray(value)) {
    return `array[${value.map(lit).join(', ')}]::text[]`;
  }
  if (typeof value === 'object') return `${lit(JSON.stringify(value))}::jsonb`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Record<string, unknown>[]): string {
  if (rows.length === 0) return '';
  const columns = Object.keys(rows[0]!);
  const values = rows.map((r) => `  (${columns.map((c) => lit(r[c])).join(', ')})`).join(',\n');
  return `insert into public.${table} (${columns.join(', ')}) values\n${values};\n`;
}

const gradeId = (level: number) => GRADES.find((g) => g.level === level)!.id;

export function referenceSql(): string {
  const offerings: Record<string, unknown>[] = [];
  let n = 0;
  for (const subject of SUBJECTS) {
    for (const level of subject.gradeLevels) {
      const streamed = (STREAM_GRADE_LEVELS as readonly number[]).includes(level) && subject.streams.length > 0;
      for (const stream of streamed ? subject.streams : [null]) {
        offerings.push({
          id: demoId('subject', 0x1000 + ++n),
          subject_id: subject.id,
          grade_id: gradeId(level),
          stream,
        });
      }
    }
  }

  return [
    '-- Reference data required in every environment (not demo content).',
    '-- Generated by supabase/scripts/generate-sql.ts from @matriq/demo-content',
    '-- catalog.ts and @matriq/core ACHIEVEMENTS. Do not edit by hand.',
    '',
    insert('grades', GRADES.map((g) => ({ id: g.id, level: g.level, name: `Grade ${g.level}` }))),
    insert('streams', STREAMS_CATALOG.map((s) => ({ id: s.id, slug: s.slug, name: s.name }))),
    insert(
      'subjects',
      SUBJECTS.map((s, i) => ({ id: s.id, slug: s.slug, name: s.name, icon_key: s.iconKey, position: i + 1 })),
    ),
    insert('subject_offerings', offerings),
    insert(
      'achievements',
      ACHIEVEMENTS.map((a, i) => ({
        id: demoId('achievement', i + 1),
        slug: a.slug,
        title: a.title,
        description: a.description,
        icon_key: a.iconKey,
        metric: a.metric,
        threshold: a.threshold,
      })),
    ),
  ].join('\n');
}

export function seedSql(): string {
  const subject = SUBJECTS.find((s) => s.slug === DEMO_EDITION.subjectSlug)!;
  const lessons: Record<string, unknown>[] = [];
  const sections: Record<string, unknown>[] = [];
  const questions: Record<string, unknown>[] = [];
  const options: Record<string, unknown>[] = [];
  const links: Record<string, unknown>[] = [];
  const cards: Record<string, unknown>[] = [];

  for (const chapter of DEMO_CHAPTERS) {
    for (const [kind, id, list] of [
      ['full', chapter.fullLessonId, chapter.fullLesson],
      ['quick_notes', chapter.quickNotesId, chapter.quickNotes],
    ] as const) {
      lessons.push({
        id,
        topic_id: chapter.id,
        kind,
        title: kind === 'full' ? `${chapter.title}: full lesson` : `${chapter.title}: quick notes`,
        source_id: DEMO_SOURCE.id,
        status: 'published',
        is_demo: true,
      });
      list.forEach((s, i) =>
        sections.push({
          id: s.id,
          lesson_id: id,
          position: i + 1,
          kind: s.kind,
          heading: s.heading,
          body: s.body,
          data: s.data,
        }),
      );
    }
    chapter.questions.forEach((q, qi) => {
      questions.push({
        id: q.id,
        origin: 'original_practice',
        prompt: q.prompt,
        explanation: q.explanation,
        hints: q.hints,
        subject_id: subject.id,
        grade_id: gradeId(DEMO_EDITION.gradeLevel),
        difficulty: q.difficulty,
        status: 'published',
        is_demo: true,
      });
      q.options.forEach((o, oi) =>
        options.push({
          id: o.id,
          question_id: q.id,
          position: oi + 1,
          label: o.label,
          body: o.body,
          is_correct: o.isCorrect,
        }),
      );
      links.push({ question_id: q.id, topic_id: chapter.id, is_primary: true, position: qi + 1 });
    });
    chapter.revisionCards.forEach((c, ci) =>
      cards.push({
        id: c.id,
        topic_id: chapter.id,
        kind: c.kind,
        position: ci + 1,
        front: c.front,
        back: c.back,
        status: 'published',
        is_demo: true,
      }),
    );
  }

  return [
    '-- DEMO CONTENT for local development and previews. Generated by',
    '-- supabase/scripts/generate-sql.ts from @matriq/demo-content. Do not edit.',
    '-- Not official EUEE material; every row is flagged is_demo = true.',
    '-- Production content must come through the content pipeline.',
    '',
    'begin;',
    '',
    insert('content_sources', [
      {
        id: DEMO_SOURCE.id,
        title: DEMO_SOURCE.title,
        kind: DEMO_SOURCE.kind,
        publisher: DEMO_SOURCE.publisher,
        license: DEMO_SOURCE.license,
        permission_status: 'granted',
        attribution: DEMO_SOURCE.attribution,
      },
    ]),
    insert('curriculum_editions', [
      {
        id: DEMO_EDITION.id,
        subject_id: subject.id,
        grade_id: gradeId(DEMO_EDITION.gradeLevel),
        stream: DEMO_EDITION.stream,
        name: DEMO_EDITION.name,
        source_id: DEMO_SOURCE.id,
        is_current: true,
        status: 'published',
        is_demo: true,
      },
    ]),
    insert(
      'units',
      DEMO_UNITS.map((u) => ({
        id: u.id,
        edition_id: DEMO_EDITION.id,
        position: u.number,
        title: u.title,
        status: 'published',
        is_demo: true,
      })),
    ),
    insert(
      'topics',
      DEMO_CHAPTERS.map((c) => ({
        id: c.id,
        unit_id: c.unitId,
        slug: c.slug,
        position: DEMO_CHAPTERS.filter((x) => x.unitId === c.unitId).indexOf(c) + 1,
        title: c.title,
        tagline: c.tagline,
        learning_objectives: c.objectives,
        status: 'published',
        is_demo: true,
      })),
    ),
    insert('lessons', lessons),
    insert('lesson_sections', sections),
    insert('questions', questions),
    insert('question_options', options),
    insert('question_topic_links', links),
    insert('revision_cards', cards),
    'commit;',
    '',
  ].join('\n');
}

function main(target: string | undefined) {
  if (target === 'reference') {
    writeFileSync(join(root, 'migrations/20261029000800_reference_data.sql'), referenceSql());
    console.log('Wrote migrations/20261029000800_reference_data.sql');
  } else if (target === 'seed') {
    writeFileSync(join(root, 'seed/demo_curriculum.sql'), seedSql());
    console.log('Wrote seed/demo_curriculum.sql');
  } else {
    console.error('Usage: generate-sql.ts reference|seed');
    process.exit(1);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv[2]);
}
